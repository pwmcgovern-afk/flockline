import { chromium } from "playwright";
const BASE = "https://flockline.app";
const SHOTS = "/private/tmp/claude-501/-Users-patrickmcgovern/18ddad7e-075c-4ab0-9e95-5e9be20b82de/scratchpad/wl-shots";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(() => { try { localStorage.setItem("flockline.tourSeen.v2", "1"); } catch {} });
const page = await ctx.newPage();
page.on("response", (r) => { if (r.url().includes("/api/")) console.log("API", r.status(), r.url().slice(0, 160)); });
await page.goto(`${BASE}/?bird=osprey&region=northeast&days=7`, { waitUntil: "networkidle" });
await page.waitForTimeout(8000);
await page.addStyleTag({ content: "*,*::before,*::after{transition:none!important;animation:none!important}" });
await page.screenshot({ path: `${SHOTS}/probe-osprey.png` });
console.log("interactive:", await page.locator(".leaflet-interactive").count());
console.log("markers:", await page.locator(".leaflet-marker-icon").count());
console.log("canvas:", await page.locator(".leaflet-container canvas").count());
console.log("body classes for dot:", await page.evaluate(() => {
  const c = document.querySelector(".leaflet-pane");
  return c ? c.innerHTML.slice(0, 1500) : "none";
}));
console.log("map-note:", await page.locator(".map-note").allInnerTexts().catch(()=>[]));
console.log("map-empty:", await page.locator(".map-empty").allInnerTexts().catch(()=>[]));
await browser.close();
